'use strict';
const assert = require('assert').strict, path = require('path'), EventEmitter = require('events');
const N = require('../service/return-navigation.js');
const load = require('./service-harness.cjs');
const frame = 'VETRO_NATIVE_PID=42\nVETRO_NAV_V1\t42\t'+'a'.repeat(32)+'\t1\t1000\t0\tapp\tvideo.two\t-\n';
const parsed = N.parse(frame);
assert.equal(parsed.appId,'video.two');assert.equal(parsed.visible,false);
for(const bad of [frame.replace('PID=42','PID=43'),frame.replace('video.two','bad;id'),frame+frame,frame.replace('\tapp\t','\tinvalid\t'),frame.replace('1000\t','NaN\t'),'']) assert.equal(N.parse(bad),null);
let now=2000;const nav=new N.Navigation(()=>now);
nav.note({kind:'app',appId:'video.three'});
assert.equal(nav.observe({full:'video.one',navigation:parsed}),true);
assert.equal(nav.intent.appId,'video.three','older native notice cannot override a newer service request');
assert.equal(nav.observe({full:'video.three',navigation:parsed}),true);
assert.equal(nav.intent,null,'observed target ends protection');
assert.equal(nav.observe({full:'video.three',navigation:parsed}),false,'same native intent is not replayed');
assert.equal(N.actionIntent({type:'key',key:'KEY_RETURN'}),null,'Back is an exit hint, not a destination');

(async()=>{
    const service=load(path.resolve(__dirname,'..'),{setTimeout:()=>({unref(){}}),setInterval:()=>({unref(){}})});
    const c=service.context;
    c.returnApp.config={version:1,appId:'home.app',revision:1};
    const commands=[];c.platform.execute=async command=>{commands.push(command);return {exit_code:0,stdout:''};};
    let release;
    c.inventory=()=>new Promise(resolve=>{release=resolve;});
    const req=new EventEmitter();req.method='POST';req.url='/apps/launch';
    const response=new Promise(resolve=>service.router(req,{writeHead(){},end(body){resolve(JSON.parse(body));}}));
    c.returnApp.pending={appId:'home.app'};
    req.emit('data',Buffer.from(JSON.stringify({appId:'video.two'})));req.emit('end');
    assert.equal(c.returnApp.pending,null,'API cancels return before slow inventory/root queue');
    assert.equal(c.returnApp.navigation.intent.appId,'video.two');
    release({apps:[{appId:'video.two'}]});await response;
    assert.equal(commands.filter(x=>x==='/usr/bin/app_launcher -s video.two').length,1);
    await c.runActions([{type:'key',key:'KEY_HOME'}]);
    assert.equal(c.returnApp.navigation.intent.kind,'home');
    await c.runActions([{type:'key',key:'KEY_TV'}]);
    assert.equal(c.returnApp.navigation.intent.kind,'input');
    c.noteRemoteActivity({action:'down',decision:'forwarded',key:'XF86Back'});
    assert.equal(c.returnApp.nextDelay(),150,'already observed physical Back advances polling');
    const until=c.returnApp.quickUntil;
    c.noteRemoteActivity({action:'repeat',decision:'forwarded',key:'XF86Back'});
    assert.equal(c.returnApp.quickUntil,until,'held repeats do not extend fast polling');
    console.log('PASS return navigation: native protocol, freshness, API capture before queue, input/Home intent, physical Back hint');
})().catch(e=>{console.error(e);process.exitCode=1;});
